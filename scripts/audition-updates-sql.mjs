#!/usr/bin/env node
// Tutti — non-destructive audition refresh for the LIVE database (Phase 5).
//
// After a seasonal re-check updates audition facts in data.json (windows, dates,
// notes, status) this prints SQL that updates the matching rows in the hosted
// database in place — no truncate, so parents' Saved lists are untouched.
// Paste the output into Supabase → SQL Editor → Run.
//
//   node scripts/audition-updates-sql.mjs > audition-updates.sql
//
// It first runs `node scripts/sync-data.mjs --check`, so it refuses to print
// anything for an invalid or out-of-sync dataset. Rows are matched by
// (org_id, position) — the curated order the seed uses. Adding or removing an
// audition (or an organization) is a different change: do that in Studio
// (CURATION.md, path A). The final SELECT lets you confirm the count matches.

import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

try {
  execFileSync(process.execPath, [join(root, "scripts", "sync-data.mjs"), "--check"], { stdio: "pipe" });
} catch (e) {
  process.stderr.write(String(e.stdout || "") + String(e.stderr || ""));
  process.stderr.write("\n✗ data.json must pass `node scripts/sync-data.mjs --check` first — nothing printed.\n");
  process.exit(1);
}

const data = JSON.parse(readFileSync(join(root, "data.json"), "utf8"));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const txt = (v) => (v == null ? "NULL" : q(v));
const dateLit = (v) => (v == null ? "NULL" : `${q(v)}::date`);
const jsonb = (v) => (v == null ? "NULL" : `${q(JSON.stringify(v))}::jsonb`);
const cmt = (s) => String(s).replace(/[\r\n]+/g, " ");

const out = [];
const w = (s = "") => out.push(s);
let n = 0;

w("-- GENERATED by scripts/audition-updates-sql.mjs from data.json — review, then run in the SQL Editor.");
w(cmt(`-- Dataset ${data.version} · generated ${data.generatedAt}. Updates audition rows in place; touches nothing else.`));
w("begin;");
w("");
for (const o of data.organizations) {
  const auds = o.auditions || [];
  if (!auds.length) continue;
  w(cmt(`-- ${o.id} — ${o.name}`));
  auds.forEach((a, i) => {
    n++;
    w(
      `update public.auditions set level = ${q(a.level)}, instruments = ${q(a.instruments)}, ` +
        `"window" = ${jsonb(a.window)}, status = ${q(a.status)}, opens_on = ${dateLit(a.opensOn)}, ` +
        `closes_on = ${dateLit(a.closesOn)}, ages = '{${a.ages.join(",")}}'::int[], note = ${txt(a.note)}, ` +
        `source = ${txt(a.source)} where org_id = ${q(o.id)} and position = ${i};`
    );
  });
  w(`update public.organizations set last_verified = ${dateLit(o.lastVerified)} where id = ${q(o.id)};`);
  w("");
}
w("commit;");
w("");
w(`-- Check: this should return ${n} (one row per audition in data.json).`);
w("select count(*) as auditions_in_database from public.auditions;");
process.stdout.write(out.join("\n") + "\n");
